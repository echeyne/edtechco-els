"""Compact result tables and appendices for the AAAI-27 Deployable AI Workshop
submission. Ported from paper/naacl2027/make_tables.py, whose condensed tables
this version keeps; only the output directory and these headers differ.

The 7-page limit cannot carry the arXiv version's eight full-width tables, so
this script condenses them into three. It formats only numbers already recorded
under paper/results/, through the same loaders and tags as
paper/analysis/generate_tables.py (imported, not copied), so a re-record that
moves RUN_TAG there moves these tables too. Nothing here is hand-typed.

The appendix tables are rebuilt here too rather than copied from the arXiv
build, because the review version differs from it: no internal artifact names
in captions (reviewers cannot open them), a shorter prompt appendix (the full
prompts ship as supplementary material), and two golden examples instead of
five. paper/tables/ and the arXiv build are left untouched.

Usage (from repo root, venv active -- the cost rows import the pipeline's own
pricing constants):
    python paper/dai2027/make_tables.py
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "analysis"))

import generate_tables as G  # noqa: E402
import make_goldens_appendix as MG  # noqa: E402

OUT = HERE / "tables"

# Textract AnalyzeDocument with the TABLES feature, first million pages, per
# page -- the API extractor.py calls. aws.amazon.com/textract/pricing/, checked
# 2026-10-31. Only used to state what the inference-only cost leaves out.
TEXTRACT_TABLES_USD_PER_PAGE = 0.015

# When the Bedrock rates in els_pipeline.metrics.BEDROCK_PRICING were confirmed
# against the AWS pricing page (task6 manifest, cost_caveat.confirmed_by).
RATES_CONFIRMED = "August--September 2026"


def header(*sources):
    return [
        "% AUTO-GENERATED by paper/dai2027/make_tables.py -- do not hand-edit.",
        f"% Source: {', '.join(sources)}",
        "% Regenerate with: python paper/dai2027/make_tables.py",
    ]


def prop(x):
    """Rates are printed as proportions, matching the body text; counts over
    golden items stay k/n so a small denominator is visible."""
    return "--" if x is None else f"{x:.3f}"


def headline(det, par, tiers, verified):
    # Recall and the depth check are uniform across states, so they move to the
    # caption. Refuse to write that caption if a re-record ever breaks it.
    for st in G.ALL_STATES:
        if det[st]["recall"] != 1.0 or not det[st]["depth_map_passed"]:
            raise SystemExit(f"{st}: recall/depth no longer uniform -- restore the columns")
    L = header(f"paper/results/task1_{G.RUN_TAG}/summary.json",
               f"task2_{G.RUN_TAG}/summary.json",
               "the signed FP audits, corpus_tiers.json")
    L += [r"\begin{table*}[t]", r"  \centering", r"  \small",
          r"  \begin{tabular}{lrrrrrrr}", r"    \toprule",
          r"    & & & \multicolumn{2}{c}{\textbf{Detection}} & "
          r"\multicolumn{3}{c}{\textbf{Parsing}} \\",
          r"    \cmidrule(lr){4-5} \cmidrule(lr){6-8}",
          r"    \textbf{State} & \textbf{pp} & \textbf{Std.} & "
          r"\textbf{Ver.\ prec.} & \textbf{Code acc.} & \textbf{Coverage} & "
          r"\textbf{Field acc.} & \textbf{Fully corr.} \\", r"    \midrule"]
    for group in (G.GOLDEN_STATES, G.HELDOUT_STATES):
        for st in group:
            d, p = det[st], par[st]
            tier = tiers["tiers"][G.STATE_TIER_KEY[st]]
            L.append(f"    {st} & {tier['only_subset']} & {p['n_parsed']} & "
                     f"{prop(verified.get(st))} & "
                     f"{d['code_matches']}/{d['code_total']} & "
                     f"{p['matched']}/{p['n_golden']} & {prop(p['field_accuracy'])} & "
                     f"{p['fully_correct']}/{p['n_golden']} \\\\")
        if group is G.GOLDEN_STATES:
            L.append(r"    \midrule")
    L += [r"    \bottomrule", r"  \end{tabular}",
          r"  \caption{Quality per state at the \emph{subset} tier "
          r"(\S\ref{sec:data}); validation states below the rule. \emph{pp}: "
          r"subset pages; \emph{Std.}: standards parsed; \emph{Ver.\ prec.}: "
          r"verified precision (\S\ref{sec:eval}). One recorded run; its recall "
          r"(1.000) and Pass-1 level count (correct) are uniform and omitted. Over "
          r"repeats (\S\ref{sec:eval-stability}), NV detector recall is 45--46/46, "
          r"code accuracy 44--45/46, and 4 NV parser strand codes vary.}",
          r"  \label{tab:headline}", r"\end{table*}"]
    return "\n".join(L) + "\n"


def levels(abl, cmp_):
    L = header(f"paper/results/task3_{G.ABLATION_TAG}/ablation_comparison.json",
               f"task4_{G.BASELINE_TAG}/baseline_comparison.json")
    a = abl["aggregate"]["pooled_by_level"]
    b = cmp_["aggregate"]["pooled_by_level"]
    L += [r"\begin{table}[t]", r"  \centering", r"  \small",
          r"  \begin{tabular}{lrrrr}", r"    \toprule",
          r"    \textbf{Level} & $n$ & \textbf{Full} & \textbf{No map} & "
          r"\textbf{Rule-based} \\", r"    \midrule"]
    for lv in ("domain", "strand", "sub_strand", "indicator"):
        n = b[lv]["llm_tp"] + b[lv]["llm_fn"]
        L.append(rf"    {lv.replace('_', '-')} & {n} & {prop(a[lv]['on_recall'])} & "
                 rf"{prop(a[lv]['off_recall'])} & "
                 rf"{prop(b[lv]['baseline_recall'])} \\")
    L += [r"    \bottomrule", r"  \end{tabular}",
          r"  \caption{Detector recall by hierarchy level, pooled over six "
          r"states: the full method, the method with the Pass-1 depth map "
          r"ablated, and a rule-based extractor graded by the same suite. Subset "
          r"tier; ablation off-arm recall varies by run (\S\ref{sec:eval-ablation}).}",
          r"  \label{tab:levels}", r"\end{table}"]
    return "\n".join(L) + "\n"


def scale(m):
    from els_pipeline.metrics import BEDROCK_PRICING
    ex, batch, per = m["executions"], m["batching_evidence"], m["per_stage_metrics"]
    L = header(f"paper/results/task6_{G.SCALE_TAG}/manifest.json")
    L.append("% Corpus tier: _trimmed -- every standard in the document, non-standards "
             "matter removed. NOT the full published PDF and NOT the _only_subset tier.")
    stages = ("depth_map_pass1", "detection", "parsing")
    usd = {}
    for st in ("KY", "CO"):
        for k in stages:
            d = per[st][k]
            r = BEDROCK_PRICING[d["model"]]
            usd[(k, st)] = (d["input_tokens"] / 1000 * r["input_per_1k"]
                            + d["output_tokens"] / 1000 * r["output_per_1k"])
    tot = {st: sum(usd[(k, st)] for k in stages) for st in ("KY", "CO")}
    ocr = {st: ex[st]["pages"] * TEXTRACT_TABLES_USD_PER_PAGE for st in ("KY", "CO")}

    def share(k, st, fmt):
        return f"{usd[(k, st)] / tot[st] * 100:{fmt}}\\%"

    def row(label, ky, co):
        return rf"    {label} & {ky} & {co} \\"

    kt, ct = per["KY"]["total"], per["CO"]["total"]
    L += [r"\begin{table}[t]", r"  \centering", r"  \small",
          r"  \setlength{\tabcolsep}{4pt}",
          r"  \begin{tabular}{lrr}", r"    \toprule",
          r"    & \textbf{KY} & \textbf{CO} \\", r"    \midrule",
          row("Pages", ex["KY"]["pages"], ex["CO"]["pages"]),
          row("Detection chunks / batches",
              f"{batch['KY']['detection_chunks']} / {batch['KY']['detection_batches']}",
              f"{batch['CO']['detection_chunks']} / {batch['CO']['detection_batches']}"),
          row("Parse batches", batch["KY"]["parse_batches"], batch["CO"]["parse_batches"]),
          row(r"Elements raw $\rightarrow$ merged",
              rf"{batch['KY']['raw_elements']}$\rightarrow${batch['KY']['after_merge_dedup']}",
              rf"{batch['CO']['raw_elements']}$\rightarrow${batch['CO']['after_merge_dedup']}"),
          row("LLM calls", kt["calls"], ct["calls"]),
          row("Input / output tokens (k)",
              f"{kt['input_tokens'] / 1000:.0f} / {kt['output_tokens'] / 1000:.0f}",
              f"{ct['input_tokens'] / 1000:.0f} / {ct['output_tokens'] / 1000:.0f}"),
          row("Wall clock", ex["KY"]["wall_clock"], ex["CO"]["wall_clock"]),
          r"    \midrule",
          row(r"\textbf{Inference cost (USD)}", rf"\textbf{{\${tot['KY']:.2f}}}",
              rf"\textbf{{\${tot['CO']:.2f}}}"),
          row(r"\quad depth map (Haiku 4.5)", share("depth_map_pass1", "KY", ".1f"),
              share("depth_map_pass1", "CO", ".1f")),
          row(r"\quad detection (Opus 4.6)", share("detection", "KY", ".0f"),
              share("detection", "CO", ".0f")),
          row(r"\quad parsing (Sonnet 4.6)", share("parsing", "KY", ".0f"),
              share("parsing", "CO", ".0f")),
          r"    \bottomrule", r"  \end{tabular}",
          r"  \caption{One batched production run per document at the "
          r"\emph{trimmed} tier: every standard in the document, front matter and "
          r"essays removed (\S\ref{sec:data}). Cost is model inference only, from "
          rf"recorded tokens at Bedrock on-demand rates confirmed in {RATES_CONFIRMED}. "
          rf"Textract OCR (\${TEXTRACT_TABLES_USD_PER_PAGE:.3f} per page, "
          rf"\${ocr['KY']:.2f} and \${ocr['CO']:.2f} here) and fixed infrastructure "
          r"are excluded.}",
          r"  \label{tab:scale}", r"\end{table}"]
    return "\n".join(L) + "\n"


def confidence(conf):
    """Same content as the arXiv table (G.build_confidence_table), restyled with
    booktabs and with the verdict rows' scope stated, since they cover only the
    in-scope detections and so do not sum to the "All" row."""
    d = conf["direct_path"]
    o = d["overall"]
    v = conf["by_audit_verdict"]
    n_scope = v["in_scope_detections_audited"]
    if sum(s["n"] for s in v["by_verdict"].values()) != n_scope:
        raise SystemExit("verdict rows no longer sum to the in-scope count")
    LABEL = {"sub_strand": "sub-strand", "matched_golden": "matched a golden",
             "real_unannotated": "real, unannotated", "real_split_title": "real, split title",
             "real_repeat_of_matched": "real, reprinted",
             "hallucinated": r"\textbf{invented}"}

    def rng(s):
        return f"{s['min']:.2f}" if s["min"] == s["max"] else f"{s['min']:.2f}--{s['max']:.2f}"

    def row(label, s):
        return (rf"    {LABEL.get(label, label)} & {s['n']} & {rng(s)} & "
                rf"{s['at_or_above_0.95']}/{s['n']} \\")

    L = header(f"paper/results/task8_{G.STATS_TAG}/confidence_distribution.json")
    L += [r"\begin{table}[t]", r"  \centering", r"  \small",
          r"  \begin{tabular}{lrrr}", r"    \toprule",
          r"    & $n$ & \textbf{Range} & $\mathbf{\geq 0.95}$ \\", r"    \midrule",
          r"    \multicolumn{4}{l}{\emph{By hierarchy level}} \\"]
    L += [row(lv, d["by_level"][lv]) for lv in ("domain", "strand", "sub_strand", "indicator")
          if lv in d["by_level"]]
    L += [r"    \midrule",
          r"    \multicolumn{4}{l}{\emph{By audit verdict (in-scope only)}} \\"]
    L += [row(k, s) for k, s in v["by_verdict"].items()]
    L += [r"    \midrule", row("All", o), r"    \bottomrule", r"  \end{tabular}"]
    guess = o["prompt_band_occupancy"]["below 0.70 (guessing)"]
    L += [r"  \caption{Detector self-reported confidence over the "
          rf"{o['n']} elements of the recorded run (subset tier). The verdict rows "
          rf"cover the {n_scope} detections inside the domains a golden annotates; "
          rf"the other {o['n'] - n_scope} were not audited. The prompt asks for "
          r"$\geq 0.95$ when the depth map clearly applies, $0.80$--$0.94$ when the "
          r"chunk is ambiguous, and $<0.70$ when guessing; the score takes "
          rf"{o['n_distinct_values']} distinct values in "
          rf"$[{o['min']:.2f}, {o['max']:.2f}]$ and uses the bottom band "
          rf"{'never' if guess == 0 else f'{guess} times'}. "
          r"\textbf{Nothing in the pipeline thresholds this score} "
          r"(\S\ref{sec:lessons}).}",
          r"  \label{tab:confidence-distribution}", r"\end{table}"]
    return "\n".join(L) + "\n"


def corpus_appendix(tiers):
    """The arXiv table with its caption's artifact names removed."""
    body = G.build_corpus_appendix_table(tiers)
    for old in (r"Page counts verified with PyMuPDF. ",
                r"Source: \texttt{standards\_tracking.md}, \texttt{corpus\_tiers.json}."):
        if old not in body:
            raise SystemExit(f"corpus_appendix: expected caption text moved: {old!r}")
        body = body.replace(old, "")
    body = body.replace("% AUTO-GENERATED by paper/analysis/generate_tables.py",
                        "% AUTO-GENERATED by paper/dai2027/make_tables.py "
                        "(via generate_tables.build_corpus_appendix_table)")
    # The arXiv caption points at sections this version does not number the same
    # way: Limitations/Ethics are unnumbered here, so \S\ref resolves to the
    # Conclusion, and Section 3 here never mentions Colorado's publication.
    for old, new in (
            (" publication (\\S\\ref{sec:corpus}).", " publication."),
            (" (\\S\\ref{sec:artifacts-statement}). }",
             " (see the Ethical Statement).}")):
        if old not in body:
            raise SystemExit(f"corpus_appendix: expected caption text moved: {old!r}")
        body = body.replace(old, new)
    return body


def corpus_pages(pr):
    """PDF page indices only. The printed-page column was blank for most rows,
    so the one mapping a reader needs to see the difference is in the caption."""
    L = header("paper/results/corpus_page_ranges.json")
    L += [r"\begin{table*}[t]", r"\centering", r"\small",
          r"\begin{tabular}{llrp{0.62\textwidth}}", r"\toprule",
          r"\textbf{State} & \textbf{Tier} & \textbf{pp} & "
          r"\textbf{Retained PDF pages} \\", r"\midrule"]
    unmatched = 0
    for st in G.ALL_STATES:
        e = pr["states"][st]
        for tier, name in (("trimmed", "trimmed"), ("only_subset", "subset")):
            t = e["tiers"].get(tier)
            if not t:
                continue
            unmatched += len(t["unmatched_tier_pages"])
            L.append(rf"{st} & {name} & {t['pages']} & "
                     rf"{t['retained_ranges_pdf_index'].replace('-', '--')} "
                     rf"(of {e['published_pages']}) \\")
    if unmatched:
        raise SystemExit(f"{unmatched} tier page(s) matched no published page")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\caption{Pages each tier retains, as indices into the published PDF "
          r"file. Printed page numbers differ by each document's front matter "
          r"(Kentucky's PDF page 52 is printed page 39). Every tier page was "
          r"matched by text to a published page. California has no trimmed tier.}",
          r"\label{tab:corpus-pages}", r"\end{table*}"]
    return "\n".join(L) + "\n"


def goldens():
    """Two of the arXiv appendix's five examples: the KY label form before and
    after parsing, and the NV namespace that skips a level. Field values come
    from the golden files through make_goldens_appendix's own readers."""

    def block(title, rows, first_col):
        return "\n".join([
            rf"{{\raggedright\noindent\textbf{{{title}}}\par}}", r"\smallskip",
            r"{\scriptsize\noindent",
            rf"\begin{{tabular}}{{@{{}}p{{{first_col}\linewidth}}"
            rf"p{{{0.94 - first_col:.2f}\linewidth}}@{{}}}}",
            r"\toprule", *rows, r"\bottomrule", r"\end{tabular}\par}", r"\medskip", ""])

    def det_rows(state, tid):
        e = MG.det(state, tid)
        return [rf"\texttt{{level}} & {MG.tt(e['level'])} \\",
                rf"\texttt{{code}} & {MG.tt(e['code'])} \\",
                rf"\texttt{{title}} & {MG.esc(e['title'])} \\"]

    def par_rows(state, tid):
        x = MG.par(state, tid)
        rows = [rf"\texttt{{standard\_id}} & {MG.tt(x['standard_id'])} \\"]
        for lvl in ("domain", "strand", "sub_strand", "indicator"):
            v = x[lvl]
            rows.append(rf"\texttt{{{MG.esc(lvl)}.code}} & {MG.tt(v['code'])} \\")
            rows.append(rf"\texttt{{{MG.esc(lvl)}.name}} & {MG.esc(v['name'])} \\")
        return rows

    parts = [
        "% AUTO-GENERATED by paper/dai2027/make_tables.py -- do not hand-edit.",
        "% Every field is copied from the golden files on disk.",
        "",
        r"The detector golden is a flat list of elements and the parser golden a "
        r"nested record per standard. The two examples below show the conventions "
        r"\S\ref{sec:method-parsing} turns on; descriptions are omitted, and codes "
        r"and identifiers are reproduced in full.",
        r"\medskip", "",
        block(r"KY detector golden: a \texttt{<Label> <id>} heading, whose "
              r"label-and-id is the code", det_rows("KY", "KY-SUB-01"), 0.22),
        block(r"KY parser golden: the same element, its label form resolved to a "
              r"domain-qualified code", par_rows("KY", "KY-STD-01"), 0.30),
        block(r"NV parser golden: a printed namespace that skips a level, so the "
              r"sub-strand code does not extend the strand's",
              par_rows("NV", "NV-STD-01"), 0.30),
    ]
    return "\n".join(parts)


def listing_after(src, label):
    """The first lstlisting following \\label{label} in the arXiv prompt appendix,
    which make_prompt_appendix.py renders from the live prompt builders."""
    i = src.index(rf"\label{{{label}}}")
    j = src.index(r"\begin{lstlisting}", i)
    k = src.index(r"\end{lstlisting}", j) + len(r"\end{lstlisting}")
    return src[j:k]


def prompt_appendix():
    src = (G.TABLES_DIR / "appendix_prompts.tex").read_text()
    n_rules = re.search(r"states (\d+) numbered extraction rules", src).group(1)
    words = {"9": "nine", "10": "ten", "8": "eight"}.get(n_rules, n_rules)
    parts = [
        "% AUTO-GENERATED by paper/dai2027/make_tables.py -- do not hand-edit.",
        "% The two listings are lifted verbatim from paper/tables/appendix_prompts.tex,",
        "% which paper/analysis/make_prompt_appendix.py renders from the live prompts.",
        "",
        r"This appendix and the schema of Appendix~\ref{sec:appendix-schema} are what "
        r"this paper discloses in place of a code release (see the Ethical Statement). "
        r"The Pass-1 prompt and the classification rule are reproduced verbatim, as the "
        r"system emits them with the document content replaced by a placeholder; the "
        r"other rules the body cites are summarized. \textbf{The complete text of all "
        r"three prompts is provided as supplementary material (\texttt{prompts.txt}).}",
        "",
        r"\subsection{Pass 1: depth-map inference}",
        r"\label{sec:prompt-depthmap}",
        r"Run once per document, on a layout-stratified sample of text blocks "
        r"(\S\ref{sec:method-detection}). Its output is supplied to every detection "
        r"call as the authority for what each nesting level is.",
        "",
        listing_after(src, "sec:prompt-depthmap"),
        "",
        r"\subsection{Pass 2: per-chunk detection}",
        r"\label{sec:prompt-detection}",
        r"The prompt opens with the canonical hierarchy, the layout-coordinate "
        rf"convention and the classification rule, then states {words} numbered "
        r"extraction rules and the output schema. Rule 1 requires every element to "
        r"be backed by a heading line that literally appears in the chunk, so a chunk "
        r"that opens part-way through a section emits the children alone and the "
        r"parent is recovered in parsing.",
        "",
        r"\subsubsection{Classification is positional}",
        r"\label{rule:positional}",
        listing_after(src, "rule:positional"),
        "",
        r"\subsubsection{Code resolution (rule 4)}",
        r"\label{rule:code-resolution}",
        r"The longest rule. \texttt{code} is required and never \texttt{null}. A "
        r"printed code always wins, and the rule orders three places to look for one: "
        r"(i)~inline on the heading line, including the \texttt{<Label> <id>} form for "
        r"any label word; (ii)~a caption beside the heading, such as a parenthetical "
        r"or column header, copied verbatim; (iii)~the shared leading prefix of the "
        r"element's descendants' dotted codes, peeled one whole segment per level, "
        r"agreed by at least two descendants, and never taken from a code that "
        r"carries a structural label word. Only when all three fail is a code of at "
        r"most five characters derived from the title: split on spaces and slashes, "
        r"drop a fixed list of connector words, then take the first four letters of a "
        r"single remaining word or the initials of up to five. That derivation is "
        r"also executed in Python (\S\ref{sec:lessons}, lesson~1).",
        "",
        r"\subsection{Parsing}",
        r"\label{sec:prompt-parsing}",
        r"The parsing prompt states the output schema, then rules for composing each "
        r"indicator's fully qualified code from its chain of ancestors. A code that is "
        r"already a dotted path beginning with its own domain's code is used as is and "
        r"never re-prefixed, at every level. A \texttt{<Label> <id>} code "
        r"(\texttt{Benchmark 1.1}) contributes only its identifier, for any label word. "
        r"Peeling ancestors off a descendant's code stops where the printed namespace "
        r"stops, so a level outside it builds its code from its own heading's "
        r"identifier (Nevada's strand \texttt{SS.1} above sub-strand \texttt{SS.ID}). "
        r"Side-by-side columns are disambiguated by a suffix on the indicator code "
        r"only: a month range for age columns (\texttt{.36-48}), otherwise the column "
        r"label's first four letters (\texttt{.DISC}). The shape repairs of "
        r"\S\ref{sec:method-parsing} that collapse a duplicated parent segment or "
        r"decline an unverifiable repair are deterministic Python applied to the "
        r"model's output, not prompt text.",
        "",
    ]
    return "\n".join(parts)


PROMPTS_HEADER = """\
Supplementary material: complete prompts
========================================

The complete text of the three prompts the system sends, exactly as the
pipeline emits them, with only the per-run document content replaced by a
placeholder. Appendix A of the submission reproduces the Pass-1 prompt and the
classification rule verbatim and summarizes the other rules it cites; this
file is the unabridged text of all three.


"""


def prompts_txt():
    """The arXiv ancillary file with a header written for the review version."""
    src = (G.PAPER_DIR / "anc" / "prompts.txt").read_text()
    m = re.search(r"^=+\n1\. PASS 1", src, re.M)
    if not m:
        raise SystemExit("prompts.txt: could not find the Pass 1 section")
    return PROMPTS_HEADER + src[m.start():]


def main():
    R = G.RESULTS_DIR
    t1 = G.load_json(R / f"task1_{G.RUN_TAG}" / "summary.json")
    t2 = G.load_json(R / f"task2_{G.RUN_TAG}" / "summary.json")
    tiers = G.load_json(R / "corpus_tiers.json")
    det = {**t1["detector"], **t2["detector"]}
    par = {**t1["parser"], **t2["parser"]}
    abl = G.load_json(R / f"task3_{G.ABLATION_TAG}" / "ablation_comparison.json")
    cmp_ = G.load_json(R / f"task4_{G.BASELINE_TAG}" / "baseline_comparison.json")
    m = G.load_json(R / f"task6_{G.SCALE_TAG}" / "manifest.json")
    conf = G.load_json(R / f"task8_{G.STATS_TAG}" / "confidence_distribution.json")
    pr = G.load_json(R / "corpus_page_ranges.json")
    OUT.mkdir(exist_ok=True)
    outputs = (
        ("headline.tex", headline(det, par, tiers, G.verified_precision_by_state())),
        ("levels.tex", levels(abl, cmp_)),
        ("scale.tex", scale(m)),
        ("confidence_distribution.tex", confidence(conf)),
        ("corpus_appendix.tex", corpus_appendix(tiers)),
        ("corpus_pages.tex", corpus_pages(pr)),
        ("appendix_goldens.tex", goldens()),
        ("appendix_prompts.tex", prompt_appendix()),
        # Hand-authored TikZ of a type structure; carries no number.
        ("fig_schema.tex", (G.TABLES_DIR / "fig_schema.tex").read_text()),
    )
    for name, body in outputs:
        (OUT / name).write_text(body)
        print(f"wrote {OUT / name}")
    (HERE / "prompts.txt").write_text(prompts_txt())
    print(f"wrote {HERE / 'prompts.txt'}")


if __name__ == "__main__":
    main()
